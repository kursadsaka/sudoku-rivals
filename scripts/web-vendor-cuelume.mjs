// Regenerates apps/web/cuelume.js from an extracted Cuelume npm package.
//
//   npm pack cuelume@0.2.8 && tar xzf cuelume-0.2.8.tgz
//   node scripts/web-vendor-cuelume.mjs ./package
//
// The web app has no bundler, so the library's ES modules are joined into one
// file in dependency order, each in its own scope. Only the default theme and the imperative API
// (play, unlock, setEnabled) are kept; the other themes and the data-attribute
// binder are not used by the app. No third-party build tool is involved.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.argv[2];
if (!root) { console.error('Usage: node scripts/web-vendor-cuelume.mjs <extracted package dir>'); process.exit(1); }
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
if (pkg.name !== 'cuelume') throw new Error(`Not the cuelume package: ${pkg.name}`);
const license = fs.readFileSync(path.join(root, 'LICENSE'), 'utf8').trim();

// Dependency order; every import below resolves to an earlier module.
const modules = ['sounds/layers.js', 'sounds/recipes.js', 'sounds/context.js', 'sounds/themes.js', 'audio/output.js', 'audio/render.js', 'audio/engine.js'];
const replaced = { 'sounds/themes.js': 'import { RECIPES } from "./recipes.js";\nexport const THEMES = { default: RECIPES };\nexport const isThemeName = value => value === "default";\n' };

// Each module becomes a scope that returns its exports, so same-named module locals cannot collide.
function scope(file) {
  const source = replaced[file] ?? fs.readFileSync(path.join(root, 'dist', file), 'utf8');
  const imports = [...source.matchAll(/^import\s*\{([^}]*)\}\s*from\s*"([^"]+)";?$/gm)].map(([, names, from]) => {
    const target = path.posix.join(path.posix.dirname(file), from);
    if (!modules.slice(0, modules.indexOf(file)).includes(target)) throw new Error(`${file}: unexpected import ${from}`);
    return `const { ${names.split(',').map(name => name.trim()).filter(Boolean).join(', ')} } = M[${JSON.stringify(target)}];`;
  });
  const exported = [...source.matchAll(/^export (?:const|let|function|class) (\w+)/gm)].map(match => match[1]);
  const body = [];
  let comment = false;
  for (const line of source.replace(/^import\s*\{[^}]*\}\s*from\s*"[^"]+";?$/gm, '').split('\n')) {
    const text = line.trim();
    if (comment) { if (text.includes('*/')) comment = false; continue; }
    if (text.startsWith('/*')) { if (!text.includes('*/')) comment = true; continue; }
    if (text.startsWith('//') || text === '') continue;
    body.push(line.replace(/^export (?=(const|let|function|class) )/, ''));
  }
  const joined = body.join('\n');
  if (/^\s*(import|export)\s/m.test(joined)) throw new Error(`${file}: unhandled import/export statement`);
  return `M[${JSON.stringify(file)}] = (() => {\n${imports.join('\n')}\n${joined}\nreturn { ${exported.join(', ')} };\n})();`;
}
const parts = modules.map(scope);
const header = `/*! cuelume ${pkg.version} — https://cuelume.dev — vendored for Sudoku Rivals.
 * Generated by scripts/web-vendor-cuelume.mjs from the npm package: modules joined,
 * comments removed, default theme and play/unlock/setEnabled only. Do not edit by hand.
 *
${license.split('\n').map(line => ` * ${line}`.trimEnd()).join('\n')}
 */`;
const target = fileURLToPath(new URL('../apps/web/cuelume.js', import.meta.url));
fs.writeFileSync(target, `${header}\nconst M = {};\n${parts.join('\n')}\nexport const { play, unlock, setEnabled } = M['audio/engine.js'];\n`);
console.log(`Wrote ${target} (${fs.statSync(target).size} bytes) from cuelume ${pkg.version}`);
